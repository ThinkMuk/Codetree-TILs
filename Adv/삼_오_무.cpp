#include <iostream>
using namespace std;

long long n;

long long cnt(long long x) {
    return x - x/3 - x/5 + x/15;
}

int main() {
    cin >> n;
    long long lo = 1, hi = 2 * n;   // 2n이면 충분히 커버함
    while (lo < hi) {
        long long mid = (lo + hi) / 2;
        if (cnt(mid) >= n) hi = mid;
        else lo = mid + 1;
    }
    cout << lo << "\n";
}
